#!/usr/bin/env python3
"""Emit bionic's generated_android_ids.h from android_filesystem_config.h.

Android 9 ships a Python 2 generator that no longer runs on this host. The
output contract is small and stable: a table of (friendly, AID_*) pairs used by
libc's getpwnam/getgrnam implementation.
"""
import re
import sys

header = open(sys.argv[1], encoding="utf-8").read()
entries = []
for match in re.finditer(r"^#define\s+AID_([A-Za-z0-9_]+)\s+([^/\n]+)", header, re.M):
    name, value = match.group(1), match.group(2).strip()
    if not re.fullmatch(r"[0-9A-Fa-fxX]+", value):
        continue
    entries.append((name.lower(), "AID_" + name))

print("/*")
print(" * THIS IS AN AUTOGENERATED FILE! DO NOT MODIFY!")
print(" */")
print("#include <private/android_filesystem_config.h>")
print()
print("struct android_id_info {")
print("    const char *name;")
print("    unsigned aid;")
print("};")
print()
print("static const struct android_id_info android_ids[] = {")
for friendly, identifier in entries:
    print('    { "%s", %s },' % (friendly, identifier))
print("};")
print()
print("#define android_id_count \\")
print("    (sizeof(android_ids) / sizeof(android_ids[0]))")
